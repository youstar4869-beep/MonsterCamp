def pal(t):
    p = dict(PALS[t])
    p["outline"] = (None, OUT[t])
    return p


def eyes(s, x, y, kind="cute", col=None):
    """x,y = top-left of LEFT eye; mirrored."""
    if kind == "cute":
        for dx, dy in ((0, 0), (1, 0), (0, 1), (1, 1), (0, 2), (1, 2)):
            s.fix(x + dx, y + dy, K, True)
        s.fix(x, y, W, True)
    elif kind == "small":
        s.fix(x, y, K, True)
        s.fix(x, y + 1, K, True)
    elif kind == "fierce":
        for dx, dy in ((0, 0), (1, 1), (2, 1), (1, 2), (2, 2)):
            s.fix(x + dx, y + dy, K, True)
        s.fix(x + 2, y + 1, col or YEL, True)
    elif kind == "sharp":
        for dx, dy in ((0, 0), (1, 0), (2, 1), (1, 1)):
            s.fix(x + dx, y + dy, K, True)
        s.fix(x + 1, y + 1, col or W, True)
    elif kind == "closed":
        s.fix(x, y + 1, K, True)
        s.fix(x + 1, y, K, True)
        s.fix(x + 2, y + 1, K, True)


def cheeks(s, x, y):
    s.fix(x, y, CH, True)


def mouth(s, y, kind="dot", cx=16):
    if kind == "dot":
        s.fix(cx - 1, y, K)
        s.fix(cx, y, K)
    elif kind == "smile":
        s.fix(cx - 2, y, K); s.fix(cx + 1, y, K)
        s.fix(cx - 1, y + 1, K); s.fix(cx, y + 1, K)
    elif kind == "fang":
        s.fix(cx - 2, y, K); s.fix(cx - 1, y, K); s.fix(cx, y, K); s.fix(cx + 1, y, K)
        s.fix(cx - 2, y + 1, W); s.fix(cx + 1, y + 1, W)
    elif kind == "w":
        s.fix(cx - 2, y, K); s.fix(cx - 1, y + 1, K); s.fix(cx, y + 1, K); s.fix(cx + 1, y, K)


def spikes(s, cx, cy, r_in, r_out, n, c, rot=0.0, ry_scale=1.0):
    import math
    pts = []
    for i in range(n * 2):
        a = rot + math.pi * i / n - math.pi / 2
        r = r_out if i % 2 == 0 else r_in
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a) * ry_scale))
    s.poly(pts, c)
